CREATE FUNCTION validate_gate_decision() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE current_status run_status;
BEGIN
  SELECT status INTO current_status FROM runs WHERE id = NEW.run_id FOR UPDATE;
  IF NEW.action = 'approve' AND (NEW.stage NOT IN ('awaiting_kpi_approval', 'awaiting_flag_review') OR current_status IS DISTINCT FROM NEW.stage OR btrim(NEW.user_id) = '') THEN
    RAISE EXCEPTION 'approval requires a user and the current gate';
  END IF;
  RETURN NEW;
END;
$$;
--> statement-breakpoint
CREATE TRIGGER validate_decision BEFORE INSERT ON human_decisions FOR EACH ROW EXECUTE FUNCTION validate_gate_decision();
